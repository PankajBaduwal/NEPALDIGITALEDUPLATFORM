async function seedClass4Science() {
  try {
    console.log('Connecting to MongoDB:', MONGODB_URI);
    await mongoose.connect(MONGODB_URI);
    console.log('Connected successfully to MongoDB.');

    console.log(`Seeding ${class4ScienceSimulations.length} Class 4 Science & Technology simulations...`);

    let insertedCount = 0;
    let updatedCount = 0;

    for (const sim of class4ScienceSimulations) {
      const res = await Simulation.findOneAndUpdate(
        { code: sim.code },
        { $set: sim },
        { upsert: true, new: true, setDefaultsOnInsert: true }
      );
      if (res.createdAt.getTime() === res.updatedAt.getTime()) {
        insertedCount++;
      } else {
        updatedCount++;
      }
      console.log(`✓ [Ch.${sim.chapterNumber}] ${sim.code} - ${sim.title} (${sim.titleNepali})`);
    }

    console.log(`\nClass 4 Science Seeding Complete!`);
    console.log(`Total Simulations: ${class4ScienceSimulations.length}`);
    console.log(`Inserted: ${insertedCount}, Updated: ${updatedCount}`);

    const allClass4Sims = await Simulation.find({ gradeLevels: 4, subjectCode: 'SCI' });
    console.log(`Verified MongoDB count for Class 4 Science: ${allClass4Sims.length}`);

    await mongoose.disconnect();
    console.log('MongoDB disconnected.');
  } catch (error) {
    console.error('Failed to seed Class 4 Science simulations:', error);
    process.exit(1);
  }
}

if (require.main === module) {
  seedClass4Science();
}

